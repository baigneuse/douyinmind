"""Provider-resolved media passes the same guarded downloader as any other source.

Network responses are local stand-ins. The decode test uses a clip generated by
the local ffmpeg, so it proves the media checks, not any CDN's behaviour.
"""
from __future__ import annotations

import hashlib
import io
import json
import shutil
import socket
import subprocess
import sys
from types import SimpleNamespace
import urllib.error

import pytest

from app.services import network_download as service
from app.services import network_download_worker as worker

SOURCE = "https://www.douyin.com/video/7000000000000000001"
A, B, C = ("https://v1.media.example.com/a/?a=1", "https://v2.media.example.com/b/?a=1",
           "https://play.media.example.com/aweme/v1/play/?video_id=x&sign=synthetic")


class Response(io.BytesIO):
    status = 200
    def __init__(self, body, url, headers=None):
        super().__init__(body)
        self.url, self.headers = url, headers or {}


def media(*urls, **extra):
    return {"candidates": [{"url": url} for url in urls], "title": "提供方标题", "author": "提供方作者", **extra}


def test_next_mirror_is_tried_after_a_refusal_and_partial_bytes_are_removed(tmp_path, monkeypatch):
    opened = []
    def open_url(request, **kwargs):
        opened.append((request.full_url, dict(request.header_items())))
        if request.full_url == A:
            raise urllib.error.HTTPError(A, 403, "Forbidden", {}, None)
        if request.full_url == B:
            return Response(b"12", B, {"Content-Length": "10"})  # Truncated transfer.
        return Response(b"complete-bytes", C, {"Content-Length": "14", "Content-Type": "video/mp4"})
    monkeypatch.setattr(worker, "_opener", lambda: SimpleNamespace(open=open_url))
    path = tmp_path / "track-0.part"
    info, size = worker._download_provided(media(A, B, C), path)
    assert [url for url, _ in opened] == [A, B, C]
    assert path.read_bytes() == b"complete-bytes" and size == 14
    assert info == {"title": "提供方标题", "uploader": "提供方作者"}
    headers = {key.lower(): value for key, value in opened[0][1].items()}
    assert headers["referer"] == "https://www.douyin.com/"
    assert not {"authorization", "cookie"} & set(headers)


def test_every_mirror_failing_reports_the_last_cause_and_leaves_no_file(tmp_path, monkeypatch):
    def refuse(request, **kwargs):
        raise urllib.error.HTTPError(request.full_url, 403, "Forbidden", {}, None)
    monkeypatch.setattr(worker, "_opener", lambda: SimpleNamespace(open=refuse))
    with pytest.raises(urllib.error.HTTPError) as error:
        worker._download_provided(media(A, B), tmp_path / "track-0.part")
    assert worker._classify(error.value) == "access_restricted"
    assert list(tmp_path.iterdir()) == []


@pytest.mark.parametrize("candidates", [
    [], [{"url": A}] * 7, [{"url": "http://127.0.0.1/private.mp4"}], [{"url": A}, {"url": "http://169.254.169.254/meta"}],
    [{"url": "file:///etc/passwd"}], [{"url": "https://user:pw@media.example.com/a.mp4"}], [{"no_url": True}], "text",
])
def test_unsafe_or_malformed_provider_addresses_are_rejected_before_any_connection(tmp_path, monkeypatch, candidates):
    monkeypatch.setattr(worker, "_opener", lambda: pytest.fail("unsafe provider media reached the network"))
    monkeypatch.setattr(service.subprocess, "Popen", lambda *a, **kw: pytest.fail("worker started for unsafe media"))
    with pytest.raises(service.NetworkDownloadError):
        worker._download_provided({"candidates": candidates}, tmp_path / "track-0.part")
    with pytest.raises(service.NetworkDownloadError):
        service.download_media(SOURCE, tmp_path / "download", progress=lambda _: None, cancelled=lambda: False,
                               media={"candidates": candidates})


def test_worker_receives_public_addresses_only_and_no_provider_credentials(tmp_path, monkeypatch):
    helper = tmp_path / "echo_worker.py"
    helper.write_text('''import json, sys
from pathlib import Path
raw = sys.stdin.buffer.readline()
request = json.loads(raw)
Path(request["target"], "media.mp4").write_bytes(b"stub-media")
Path(request["target"]).parent.joinpath("request.json").write_bytes(raw)
print(json.dumps({"event": "result", "filename": "media.mp4", "duration_ms": 1000,
                  "title": request["media"]["title"], "author": request["media"]["author"]}), flush=True)
''', encoding="utf-8")
    original = subprocess.Popen
    monkeypatch.setattr(service.subprocess, "Popen", lambda args, **kwargs: original([sys.executable, "-I", "-B", str(helper)], **kwargs))
    monkeypatch.setattr(service, "_media_tool", lambda _: sys.executable)
    monkeypatch.setattr(service.importlib.util, "find_spec", lambda name: None)  # Provider media needs no extractor.
    monkeypatch.setenv("TIKHUB_API_KEY", "environment-token-must-not-be-inherited")
    target = tmp_path / "attempt" / "download"
    result = service.download_media(SOURCE, target, progress=lambda _: None, cancelled=lambda: False,
                                    media=media(A, B, token="provider-token", cookie="sessionid=1", title="标题\x00"))
    assert result["title"] == "标题" and result["author"] == "提供方作者"
    assert result["sha256"] == hashlib.sha256(b"stub-media").hexdigest()
    request = json.loads((tmp_path / "attempt" / "request.json").read_text(encoding="utf-8"))
    assert request["media"] == {"candidates": [{"url": A}, {"url": B}], "title": "标题", "author": "提供方作者"}
    assert request["url"] == SOURCE and request["deno"] is None
    assert "token" not in json.dumps(request) and "sessionid" not in json.dumps(request)
    assert "environment-token" not in json.dumps(service._worker_environment(target))


def test_oversized_worker_input_is_refused(tmp_path):
    long = "https://v1.media.example.com/" + "a" * 4000
    with pytest.raises(service.NetworkDownloadError) as error:
        service.download_media(SOURCE, tmp_path / "download", progress=lambda _: None, cancelled=lambda: False,
                               media=media(*[long + str(index) for index in range(6)]))
    assert error.value.code == "invalid_source"


def test_provider_media_is_fully_decoded_and_published_by_the_real_local_pipeline(tmp_path, monkeypatch, capsys):
    ffmpeg, ffprobe = shutil.which("ffmpeg"), shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        pytest.skip("Local ffmpeg/ffprobe are not installed")
    clip = tmp_path / "generated.mp4"
    subprocess.run([ffmpeg, "-nostdin", "-v", "error", "-f", "lavfi", "-i", "testsrc=size=320x568:rate=15:duration=2",
                    "-f", "lavfi", "-i", "sine=frequency=440:duration=2", "-c:v", "libx264", "-pix_fmt", "yuv420p",
                    "-c:a", "aac", "-shortest", "-movflags", "+faststart", str(clip)], check=True, timeout=120)
    body = clip.read_bytes()
    def open_url(request, **kwargs):
        if request.full_url == A:
            return Response(b"<html>expired</html>", A, {"Content-Type": "text/html"})
        return Response(body, B, {"Content-Length": str(len(body)), "Content-Type": "video/mp4"})
    monkeypatch.setattr(worker, "_opener", lambda: SimpleNamespace(open=open_url))
    monkeypatch.setattr(socket.socket, "connect", lambda *a: pytest.fail("pipeline test must not connect"))
    monkeypatch.setattr(worker, "_extract", lambda *a, **kw: pytest.fail("provider media must not invoke the extractor"))
    target = tmp_path / "download"
    target.mkdir()
    worker.run({"url": SOURCE, "target": str(target), "ffprobe": ffprobe, "ffmpeg": ffmpeg, "deno": None,
                "media": media(A, B)})
    events = [json.loads(line) for line in capsys.readouterr().out.splitlines()]
    result = events[-1]
    assert result["event"] == "result" and result["filename"] == "media.mp4"
    assert 1800 <= result["duration_ms"] <= 2300 and result["title"] == "提供方标题" and result["author"] == "提供方作者"
    assert (target / "media.mp4").read_bytes() == body
    assert [path.name for path in target.iterdir()] == ["media.mp4"]


def test_provider_media_that_is_not_a_video_fails_the_integrity_check(tmp_path, monkeypatch):
    ffmpeg, ffprobe = shutil.which("ffmpeg"), shutil.which("ffprobe")
    if not ffmpeg or not ffprobe:
        pytest.skip("Local ffmpeg/ffprobe are not installed")
    monkeypatch.setattr(worker, "_opener", lambda: SimpleNamespace(open=lambda request, **kw: Response(
        b"not-a-video" * 100, A, {"Content-Type": "video/mp4"})))
    target = tmp_path / "download"
    target.mkdir()
    with pytest.raises(service.NetworkDownloadError) as error:
        worker.run({"url": SOURCE, "target": str(target), "ffprobe": ffprobe, "ffmpeg": ffmpeg, "deno": None, "media": media(A)})
    assert error.value.code == "invalid_media"
    assert not (target / "media.mp4").exists()
